<?php

namespace App\Http\Controllers\Owner;

use App\Http\Controllers\Controller;
use Illuminate\Http\RedirectResponse;
use Illuminate\Notifications\DatabaseNotification;
use Illuminate\View\View;

class NotificationController extends Controller
{
    public function index(): View
    {
        $notifications = auth()->user()->notifications()->latest()->paginate(15);
        return view('pages.owner.notifications.index', compact('notifications'));
    }

    public function open(string $notificationId): RedirectResponse
    {
        $notification = $this->ownedNotification($notificationId);
        $notification->markAsRead();
        $target = data_get($notification->data, 'action_url');
        $fallback = route('owner.notifications.index');
        $path = is_string($target) ? parse_url($target, PHP_URL_PATH) : null;
        // Only permit internal relative paths generated by this application.
        if (! is_string($path) || ! str_starts_with($path, '/owner/')) $target = $fallback;
        return redirect()->to($target);
    }

    public function markAsRead(string $notificationId): RedirectResponse
    {
        $this->ownedNotification($notificationId)->markAsRead();
        return back()->with('success', 'Notifikasi ditandai sudah dibaca.');
    }

    public function markAllAsRead(): RedirectResponse
    {
        auth()->user()->unreadNotifications()->update(['read_at' => now()]);
        return back()->with('success', 'Semua notifikasi ditandai sudah dibaca.');
    }

    private function ownedNotification(string $id): DatabaseNotification
    {
        return auth()->user()->notifications()->whereKey($id)->firstOrFail();
    }
}
