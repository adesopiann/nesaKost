<?php

namespace App\Http\Controllers\Tenant;

use App\Http\Controllers\Controller;
use Illuminate\Http\RedirectResponse;
use Illuminate\Notifications\DatabaseNotification;
use Illuminate\View\View;

class NotificationController extends Controller
{
    public function index(): View
    {
        $notifications = auth()->user()
            ->notifications()
            ->latest()
            ->paginate(10);

        return view('pages.tenant.notifications.index', compact('notifications'));
    }

    public function open(string $notificationId): RedirectResponse
    {
        $notification = $this->findOwnedNotification($notificationId);
        $notification->markAsRead();

        $target = data_get($notification->data, 'action_url');
        $fallback = route('tenant.notifications.index');

        // Accept validated internal paths and same-host absolute URLs generated by route().
        // External hosts, unsafe schemes, protocol-relative URLs and backslashes are rejected.
        if (! is_string($target) || $target === '' || str_contains($target, '\\')) {
            return redirect()->to($fallback);
        }

        $parts = parse_url($target);
        if (! is_array($parts)) {
            return redirect()->to($fallback);
        }

        $path = $parts['path'] ?? null;
        $validPath = is_string($path)
            && str_starts_with($path, '/tenant/')
            && ! str_starts_with($path, '//')
            && ! str_contains($path, '\\');

        if (! $validPath || isset($parts['user']) || isset($parts['pass'])) {
            return redirect()->to($fallback);
        }

        // If an absolute URL is supplied, require its host to match this request's host.
        if (isset($parts['scheme']) || isset($parts['host'])) {
            $scheme = strtolower((string) ($parts['scheme'] ?? ''));
            $host = strtolower((string) ($parts['host'] ?? ''));
            $requestHost = strtolower(request()->getHost());

            if (! in_array($scheme, ['http', 'https'], true) || $host !== $requestHost) {
                return redirect()->to($fallback);
            }

            // Reject mismatched explicit ports as well, while allowing URLs without a port.
            $targetPort = $parts['port'] ?? null;
            $requestPort = request()->getPort();
            if ($targetPort !== null && (int) $targetPort !== (int) $requestPort) {
                return redirect()->to($fallback);
            }
        }

        // Rebuild using only the validated internal path and query string.
        $safeTarget = $path . (isset($parts['query']) ? '?' . $parts['query'] : '');
        return redirect()->to($safeTarget);
    }

    public function markAsRead(string $notificationId): RedirectResponse
    {
        $this->findOwnedNotification($notificationId)->markAsRead();

        return back()->with('success', 'Notifikasi ditandai sudah dibaca.');
    }

    public function markAllAsRead(): RedirectResponse
    {
        auth()->user()->unreadNotifications()->update(['read_at' => now()]);

        return back()->with('success', 'Semua notifikasi ditandai sudah dibaca.');
    }

    private function findOwnedNotification(string $notificationId): DatabaseNotification
    {
        return auth()->user()
            ->notifications()
            ->whereKey($notificationId)
            ->firstOrFail();
    }
}
